"""Writes src/data/focal.ts: a focal point (0..1) for every image in public/images.

Film artwork is mostly 16:9 trailer thumbnails. When it is cropped to a tall
poster card, the crop is centred on the faces OpenCV finds (largest faces count
most), so posters show people rather than the gap between them.
Usage: python scripts/focal_points.py
"""
import json
import os
import cv2
import numpy as np

ROOT = "public/images"
OUT = "src/data/focal.ts"
front = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_frontalface_default.xml")
profile = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_profileface.xml")

def faces(gray):
    h = gray.shape[0]
    min_size = (max(24, h // 14), max(24, h // 14))
    found = []
    for cascade, flip in ((front, False), (profile, False), (profile, True)):
        g = cv2.flip(gray, 1) if flip else gray
        for (x, y, w, hh) in cascade.detectMultiScale(g, scaleFactor=1.1, minNeighbors=6, minSize=min_size):
            if flip:
                x = gray.shape[1] - x - w
            found.append((x, y, w, hh))
    return found

result = {}
for name in sorted(os.listdir(ROOT)):
    if not name.lower().endswith((".jpg", ".jpeg", ".png", ".webp")):
        continue
    img = cv2.imread(os.path.join(ROOT, name))
    if img is None:
        continue
    H, W = img.shape[:2]
    gray = cv2.equalizeHist(cv2.cvtColor(img, cv2.COLOR_BGR2GRAY))
    fs = faces(gray)
    if fs:
        weights = np.array([w * h for (_, _, w, h) in fs], dtype=float) ** 1.5
        cx = np.array([x + w / 2 for (x, _, w, _) in fs]) / W
        cy = np.array([y + h / 2 for (_, y, _, h) in fs]) / H
        fx, fy = float((cx * weights).sum() / weights.sum()), float((cy * weights).sum() / weights.sum())
    else:
        fx, fy = 0.5, 0.4
    result[f"/images/{name}"] = {"x": round(fx, 3), "y": round(fy, 3), "w": W, "h": H, "faces": len(fs)}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/focal_points.py. Do not edit by hand.\n")
    f.write("// Focal point (0..1) of each image, used to crop wide artwork into tall cards.\n\n")
    f.write("export const focal: Record<string, { x: number; y: number; w: number; h: number; faces: number }> = ")
    f.write(json.dumps(result, indent=2))
    f.write(";\n")
print("images:", len(result), "with faces:", sum(1 for v in result.values() if v["faces"]))

"""Saves a clean still frame from each featured film's trailer (for the Netflix-style row).

YouTube publishes frames from inside every video (maxres2.jpg is taken around the
middle). Unlike the promotional thumbnails they carry no "TRAILER" text, so the
official title logo can sit on top. Cinema letterbox bars are trimmed off.
Also takes one chosen frame (1-3) from each upcoming project's glimpse, for the
home page's Coming soon reel.
Writes public/images/frames/<slug>.jpg and src/data/frames.ts.

Usage: python scripts/fetch_trailer_frames.py
"""
import io
import json
import os
import re
import urllib.request

import numpy as np
from PIL import Image

OUT_DIR = "public/images/frames"

# Upcoming projects: (glimpse video, which in-video frame), chosen by eye.
UPCOMING = {
    "rowdy-janardhana": ("Q1s_CWfGAHk", 2),
    "yellamma": ("6SaQ3mey3-A", 2),
    "dethadi": ("ldJToRagYqs", 1),
}


def featured_slugs():
    text = open("src/data/site.ts", encoding="utf-8").read()
    block = re.search(r"export const heroSlugs = \[([\s\S]*?)\]", text).group(1)
    return re.findall(r'"([^"]+)"', block)


def films():
    text = open("src/data/films.ts", encoding="utf-8").read()
    return {f["slug"]: f for f in json.loads(re.search(r"=\s*(\[[\s\S]*\]);?\s*$", text).group(1))}


def trim_letterbox(im):
    """Drop near-black rows at the top and bottom (scope trailers are letterboxed)."""
    a = np.asarray(im.convert("L")).astype(float)
    rows = np.where(a.mean(axis=1) > 18)[0]
    if len(rows) == 0:
        return im
    return im.crop((0, int(rows[0]), im.width, int(rows[-1]) + 1))


def save_frame(slug, vid, n):
    req = urllib.request.Request(f"https://i.ytimg.com/vi/{vid}/maxres{n}.jpg", headers={"User-Agent": "SVC-website-build/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        im = Image.open(io.BytesIO(r.read())).convert("RGB")
    im = trim_letterbox(im)
    im.save(f"{OUT_DIR}/{slug}.jpg", quality=86, optimize=True, progressive=True)
    print(slug, im.size)
    return {"src": f"/images/frames/{slug}.jpg", "w": im.width, "h": im.height}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    catalogue = films()
    frames = {}
    for slug in featured_slugs():
        vid = catalogue[slug].get("trailer")
        if vid:
            frames[slug] = save_frame(slug, vid, 2)
    for slug, (vid, n) in UPCOMING.items():
        frames[slug] = save_frame(slug, vid, n)
    with open("src/data/frames.ts", "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/fetch_trailer_frames.py. Do not edit by hand.\n")
        f.write("// A clean still from each featured trailer (YouTube frame, letterbox trimmed).\n\n")
        f.write("export const trailerFrames: Record<string, { src: string; w: number; h: number }> = ")
        f.write(json.dumps(frames, indent=2))
        f.write(";\n")


if __name__ == "__main__":
    main()

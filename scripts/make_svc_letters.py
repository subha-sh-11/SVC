"""Builds public/brand/svc-letters.svg (the word "SVC" as outlines in Playfair Display)
and src/data/svcLetterCells.ts (the grid cells the letters cover, for the intro's posters).

The intro shows SVC's film posters through these letters, so they are cut in the
site's traditional serif (Playfair Display, Black) rather than a generic sans.
Font: Playfair Display variable TTF from github.com/google/fonts (SIL OFL).

Usage: python scripts/make_svc_letters.py <PlayfairDisplay[wght].ttf> [weight]
"""
import sys
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

TEXT = "SVC"
TRACKING = 40  # extra font units between letters
OUT = "public/brand/svc-letters.svg"
CELLS_OUT = "src/data/svcLetterCells.ts"
COLS = 14  # at 14 columns of 2:3 tiles the letters cover exactly 47 cells: one per SVC production

font = TTFont(sys.argv[1])
weight = float(sys.argv[2]) if len(sys.argv) > 2 else 900
if "fvar" in font:
    font = instancer.instantiateVariableFont(font, {"wght": weight})

glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
hmtx = font["hmtx"]

# Lay the letters out left to right, flipping y (fonts are y-up, SVG is y-down).
pen = SVGPathPen(glyphs)
bounds = BoundsPen(glyphs)
x = 0
placed = []
for ch in TEXT:
    name = cmap[ord(ch)]
    placed.append((name, x))
    for target in (pen, bounds):
        glyphs[name].draw(TransformPen(target, (1, 0, 0, -1, x, 0)))
    x += hmtx[name][0] + TRACKING

xmin, ymin, xmax, ymax = bounds.bounds
w, h = xmax - xmin, ymax - ymin
svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{xmin:.0f} {ymin:.0f} {w:.0f} {h:.0f}">'
    f'<path fill="#000" d="{pen.getCommands()}"/></svg>\n'
)
open(OUT, "w", encoding="utf-8").write(svg)
print(OUT, f"aspect {w:.0f}/{h:.0f}")


def inside(px, py):
    """Is an SVG-space point (y down) inside any letter?"""
    for name, ox in placed:
        p = PointInsidePen(glyphs, (px - ox, -py))
        glyphs[name].draw(p)
        if p.getResult():
            return True
    return False


# Grid of 2:3 tiles over the letters' box; keep every cell that touches a letter.
cw = w / COLS
chh = cw * 1.5
rows = int(-(-h // chh))
cells = []
for r in range(rows):
    for c in range(COLS):
        if any(inside(xmin + (c + (sx + 0.5) / 6) * cw, ymin + (r + (sy + 0.5) / 6) * chh) for sx in range(6) for sy in range(6)):
            cells.append([c, r])
with open(CELLS_OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/make_svc_letters.py. Do not edit by hand.\n")
    f.write("// Grid cells (column, row) of 2:3 tiles that the SVC letters cover; one poster per cell.\n\n")
    f.write(f"export const letterGrid = {{ cols: {COLS}, rows: {rows}, cells: {cells} as [number, number][] }};\n")
    f.write("\n// The letters' outline (same coordinates as svc-letters.svg), for the gold rim drawn around them.\n")
    f.write(f'export const letterOutline = {{ viewBox: "{xmin:.0f} {ymin:.0f} {w:.0f} {h:.0f}", d: "{pen.getCommands()}" }};\n')
print(CELLS_OUT, f"{COLS} cols x {rows} rows, {len(cells)} cells")
